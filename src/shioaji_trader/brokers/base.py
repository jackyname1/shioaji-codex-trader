from __future__ import annotations

from datetime import datetime
from typing import Protocol

from ..models import Account, Instrument, Order, Quote


class Broker(Protocol):
    production: bool

    def connect(self) -> None: ...
    def close(self) -> None: ...
    def account(self, now: datetime) -> Account: ...
    def instruments(self, symbols: list[str], now: datetime) -> dict[str, Instrument]: ...
    def discover(self, count: int, now: datetime) -> list[dict]: ...
    def history(self, symbol: str, now: datetime) -> list[dict]: ...
    def subscribe(self, symbols: list[str], whole_lots: bool = False) -> None: ...
    def quotes(self, now: datetime) -> list[Quote]: ...
    def submit(self, order: Order) -> Order: ...
    def cancel(self, order: Order) -> Order: ...
    def reconcile(self, orders: list[Order]) -> list[Order]: ...
